"""Build a plugin bundle from a Git archive of the common plugins directory."""

import argparse
import gzip
import hashlib
import io
import json
import re
import tarfile
from pathlib import Path, PurePosixPath


def build_package(snapshot, identifier, output):
    if not re.fullmatch(r"[a-z][a-z0-9_-]*", identifier):
        raise ValueError("Invalid plugin identifier")
    files = {}
    with tarfile.open(snapshot, "r:*") as archive:
        for member in archive:
            name = member.name
            if name != "LICENSE" and not name.startswith(identifier + "/"):
                continue
            path = PurePosixPath(name)
            if path.is_absolute() or ".." in path.parts or str(path) != name:
                raise ValueError("Noncanonical archive path")
            if member.isdir():
                continue
            if not member.isfile():
                raise ValueError("Plugin archive must contain regular files only")
            if name in files:
                raise ValueError("Duplicate archive entry")
            stream = archive.extractfile(member)
            if stream is None:
                raise ValueError("Unreadable archive entry")
            with stream:
                files[name] = stream.read()

    manifest_path = f"{identifier}/plugin.json"
    manifest = json.loads(files[manifest_path])
    if manifest["id"] != identifier:
        raise ValueError("Manifest identifier mismatch")
    version = manifest["version"]
    if not isinstance(version, str) or not re.fullmatch(r"[0-9A-Za-z][0-9A-Za-z.+-]*", version):
        raise ValueError("Invalid plugin version")
    module = manifest["module"]
    if not isinstance(module, str) or not re.fullmatch(r"[A-Za-z_][A-Za-z0-9_]*", module):
        raise ValueError("Invalid plugin module")
    if type(manifest["api_version"]) is not int or manifest["api_version"] < 1:
        raise ValueError("Invalid API version")
    source_prefix = f"{identifier}/src/{module}/"
    if source_prefix + "__init__.py" not in files:
        raise ValueError("Missing plugin entry point")
    license_path = f"{identifier}/LICENSE"
    license_data = files.get(license_path, files.get("LICENSE"))
    if not license_data:
        raise ValueError("Missing license")
    selected = {manifest_path: files[manifest_path], license_path: license_data}
    for name, data in files.items():
        if name.startswith(source_prefix):
            path = PurePosixPath(name)
            if "__pycache__" in path.parts or path.suffix in {".pyc", ".pyo"}:
                raise ValueError("Generated bytecode must not be distributed")
            selected[name] = data

    # Normalize member metadata and gzip headers for byte-identical builds.
    payload = io.BytesIO()
    with (
        gzip.GzipFile(fileobj=payload, mode="wb", filename="", mtime=0) as compressed,
        tarfile.open(fileobj=compressed, mode="w", format=tarfile.USTAR_FORMAT) as archive,
    ):
        for name, data in sorted(selected.items()):
            member = tarfile.TarInfo(name)
            member.size = len(data)
            member.mode = 0o644
            archive.addfile(member, io.BytesIO(data))
    data = payload.getvalue()
    output = Path(output)
    output.mkdir(parents=True, exist_ok=True)
    package = output / f"termia-plugin-{identifier}-{version}.tar.gz"
    checksum = output / (package.name + ".sha256")
    if package.exists() or checksum.exists():
        raise FileExistsError("Output already exists; choose another directory")
    with package.open("xb") as stream:
        stream.write(data)
    with checksum.open("x", encoding="utf-8") as stream:
        stream.write(f"{hashlib.sha256(data).hexdigest()}  {package.name}\n")
    return package, checksum


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("plugin")
    parser.add_argument("--snapshot", type=Path, required=True,
                        help="Git tar archive rooted at the common plugins directory")
    parser.add_argument("--output", type=Path, required=True)
    args = parser.parse_args()
    try:
        package, checksum = build_package(args.snapshot, args.plugin, args.output)
    except (OSError, ValueError, KeyError, tarfile.TarError) as error:
        parser.exit(1, f"Cannot package plugin: {error}\n")
    print(package)
    print(checksum)


if __name__ == "__main__":
    main()
